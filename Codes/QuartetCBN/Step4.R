Geno10<-read.table("./Data/Real_Data/Genotypes/Glioblastoma_Multiforme.dat")
Sample.Size<-dim(Geno10)[1]
Quartets<-combn(10,4)
N.Quartets<-choose(10,4)
nGenes<-4

  
### CT-CBN
#################################################################################################################
#################################################################################################################
sink(file="./Codes/QuartetCBN/Step4C.sh")
for (i in 1:N.Quartets){
  cat(paste0("./ct-cbn-0.1.04b/ct-cbn -f ./Data/Real_Data/Quartets/C/Genotype",i," -e -1>>./Data/Real_Data/Quartets/C/Results",i,".dat\n"))
}
sink(file = NULL)
#################################################################################################################
#################################################################################################################


### H-CBN
#################################################################################################################
#################################################################################################################
sink(file="./Codes/QuartetCBN/Step4H.sh")
for (i in 1:N.Quartets){
  cat(paste0("./ct-cbn-0.1.04b/H-cbn -f ./Data/Real_Data/Quartets/H/Genotype",i," -s -T 1 -N 10000 -w\n"))
}
sink(file = NULL)
#################################################################################################################
#################################################################################################################

### B-CBN
#################################################################################################################
#################################################################################################################
sink(file="./Codes/QuartetCBN/Step4B.sh")
for (i in 1:N.Quartets){
      cat(paste0("Rscript --vanilla ./Codes/QuartetCBN/Step4B.R ",i,"\n"))
}
sink(file = NULL)
#################################################################################################################
#################################################################################################################


### R-CBN
###########################################################################################################################################################
##### Generating the script files #########################################################################################################################
sink(file="./Codes/QuartetCBN/Step4R.sh")
for (i in 1:N.Quartets){# different quartets
  for (j in 1:219){# all 219 unique transitively-closed DAGs of restrictons
    cat(paste0("cp ./Data/Posets4/poset",j,".dat ./Data/Real_Data/Quartets/R/Genotype",i,".poset"))
    cat("\n")
    cat(paste0("./ct-cbn-0.1.04b/ct-cbn -f ./Data/Real_Data/Quartets/R/Genotype",i,"|tail -1>>./Data/Real_Data/Quartets/R/Results",i,".dat"))
    cat("\n")
    cat(paste0("rm ./Data/Real_Data/Quartets/R/Genotype",i,".poset"))
    cat("\n")
  }
}
sink(file = NULL)
