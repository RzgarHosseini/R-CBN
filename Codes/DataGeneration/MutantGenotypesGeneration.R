Matrix_Mutator<-function(mat,FP,FN){
  #mat: matrix of genotype samples that needs to be muatated
  #FP: False positive rate
  #FN: False negative rate
  d<-dim(mat)[1]
  AllP<-which(mat==1)
  AllN<-which(mat==0)
  Sample_FP<-AllN[sample(1:length(AllN),round(FP*length(AllN)))]
  Sample_FN<-AllP[sample(1:length(AllP),round(FN*length(AllP)))]
  
  for (i in 1:length(Sample_FP)){
    x<-Sample_FP[i]%%d
    y<-ceiling(Sample_FP[i]/d)
    mat[x,y]<-1
  }
  
  for (i in 1:length(Sample_FN)){
    x<-Sample_FN[i]%%d
    y<-ceiling(Sample_FN[i]/d)
    mat[x,y]<-0
  }
  
  return(mat)
}


########################################################################################################################################################################################################################################################################################
########################################################################################################################################################################################################################################################################################
########################################################################################################################################################################################################################################################################################
### Example I: Generating mutated (synthetic) genotypes of varying FP and FN rates [Without mutual exclusivity]
FP<-c(0.0,0.1,0.2,0.3)
FN<-c(0.0,0.1,0.2,0.3)
for (i in 1:219){
  Samples<-read.table(file=paste("./Data/Synthetic_Data/Genotypes/Without_Mutual_Exclusivity/genotype",i,".dat",sep=""))
  for (j in 1:4){
    for (k in 1:4){
      Mutated_Samples<-Matrix_Mutator(Samples,FP[j],FN[k])
      write(t(Mutated_Samples),file=paste("./Data/Synthetic_Data/Genotypes/Without_Mutual_Exclusivity/Mutated_genotype",i,"_",FP[j],"_",FN[k],".dat",sep=""),ncolumns=4,append=TRUE,sep=" ")
    }
  }  
}



